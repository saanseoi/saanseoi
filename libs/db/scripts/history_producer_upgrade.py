"""Retain dataset ownership while applying the generated HISTORY schema migration.

DDL stays generated by Drizzle. The local migration runner owns the backup and
transaction; this hook validates META ownership before any DDL, then fills the new
geometry discriminator while the old release reference is still available.
"""
from contextlib import closing
import re
import sqlite3
from pathlib import Path

MIGRATION = '20261015070540_luxuriant_garia/migration.sql'
GEOMETRY = {'divisionAreas', 'divisionBoundaries'}


def quote(name):
    return '"' + name.replace('"', '""') + '"'


def upgrade(db, sql, split_statements, metadata=None):
    tables = []
    for (name,) in db.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchall():
        columns = {row[1] for row in db.execute(f'PRAGMA table_info({quote(name)})')}
        if {'snapshotId', 'sourceReleaseId', 'operation'} <= columns:
            tables.append((name, columns))
    snapshots = set()
    for name, _ in tables:
        snapshots.update(row[0] for row in db.execute(f'SELECT DISTINCT snapshotId FROM {quote(name)}'))
    if snapshots and metadata is None:
        raise ValueError('Populated HISTORY ownership migration requires --metadata; no release columns were removed.')
    producers = {}
    if snapshots:
        with closing(sqlite3.connect(Path(metadata).resolve().as_uri() + '?mode=ro', uri=True)) as meta:
            meta.execute('BEGIN')
            for snapshot, release, dataset in meta.execute('''SELECT m.snapshotId,m.resourceReleaseId,d.code
                FROM snapshotResourceReleases m
                JOIN resourceReleaseDetails r ON r.id=m.resourceReleaseId
                JOIN datasets d ON d.id=r.datasetId WHERE m.role='primary' '''):
                if snapshot not in snapshots:
                    continue
                inputs = producers.setdefault(snapshot, {})
                if dataset in inputs:
                    raise ValueError(f'Snapshot {snapshot} has competing HISTORY producers for dataset {dataset}.')
                inputs[dataset] = release
        for snapshot in snapshots:
            if not producers.get(snapshot):
                raise ValueError(f'Snapshot {snapshot} has no primary HISTORY producer; ownership was not changed.')
    fills = {}
    before = {}
    for table, columns in tables:
        before[table] = db.execute(f'SELECT count(*) FROM {quote(table)}').fetchone()[0]
        if table in GEOMETRY:
            assignments = set()
            for snapshot, release in db.execute(f'''SELECT DISTINCT snapshotId,sourceReleaseId
                    FROM {quote(table)} WHERE operation='upsert' '''):
                inputs = producers[snapshot]
                datasets = [dataset for dataset, owner in inputs.items() if owner == release]
                if len(datasets) != 1:
                    raise ValueError(f'{table}/{snapshot}: retained release {release} is not an unambiguous primary producer.')
                if len(inputs) > 1:
                    assignments.add((datasets[0], snapshot, release))
            fills[table] = assignments
        else:
            dataset = ',datasetCode' if 'datasetCode' in columns else ''
            for row in db.execute(f'''SELECT DISTINCT snapshotId,sourceReleaseId{dataset}
                    FROM {quote(table)} WHERE operation='upsert' '''):
                snapshot, release = row[:2]
                inputs = producers[snapshot]
                owner = next(iter(inputs.values())) if len(inputs) == 1 else inputs.get(row[2] if dataset else None)
                if owner != release:
                    raise ValueError(f'{table}/{snapshot}: retained release {release} cannot be derived from snapshot inputs.')
    for statement in split_statements(sql):
        clean = re.sub(r'-->[^\n]*\n', '', statement).strip()
        if re.match(r'INSERT INTO [`"]__new_(divisionAreas|divisionBoundaries)[`"]', clean):
            # Drizzle omits added columns from rebuild copies; retain the converted discriminator.
            statement = statement.replace('`id`,', '`producerDatasetCode`, `id`,')
        added = re.match(r'ALTER TABLE [`"]?(divisionAreas|divisionBoundaries)[`"]? ADD [`"]?producerDatasetCode\b', clean, re.I)
        existing = None
        if added:
            existing = next((row for row in db.execute(f'PRAGMA table_info({quote(added[1])})')
                             if row[1] == 'producerDatasetCode'), None)
            if existing is not None and (existing[2].upper(), existing[3], existing[4], existing[5]) != ('TEXT', 0, None, 0):
                raise ValueError(f'{added[1]} has an incompatible producerDatasetCode column; ownership was not changed.')
        # A local shard can already contain the conversion under a different
        # generated migration receipt. Rebuild it normally, retaining its dataset
        # discriminators, rather than adding the same nullable TEXT column twice.
        if existing is None:
            db.execute(statement)
        if added and added[1] in fills:
            table = added[1]
            db.executemany(f'''UPDATE {quote(table)} SET producerDatasetCode=?
                WHERE snapshotId=? AND sourceReleaseId=? AND operation='upsert' ''', fills.get(table, ()))
    for table, count in before.items():
        if db.execute(f'SELECT count(*) FROM {quote(table)}').fetchone()[0] != count:
            raise ValueError(f'HISTORY ownership migration changed the number of events in {table}.')
